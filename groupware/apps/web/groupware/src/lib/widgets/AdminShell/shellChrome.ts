/**
 * 관리자 셸 크롬의 페이지별 선택
 *
 * 페이지가 자기 load 에서 `chrome` 으로 주입하고 셸이 읽는다. 서브 앱바가 `page.data.subAppBar`
 * 를 쓰는 것과 같은 관용이며, 이유도 같다. 셸 위젯이 라우트 목록을 들고 "이 경로면 감춘다" 를
 * 판단하기 시작하면, 화면이 늘 때마다 그 목록을 함께 고쳐야 하고 빠뜨려도 아무것도 알려주지 않는다.
 *
 * 생산자(페이지)와 소비자(셸)가 이 선언 하나를 공유한다. page.data 는 라우트마다 형태가 달라
 * SvelteKit 이 타입을 주지 않으므로, 셸은 이 타입으로 한 번만 좁히고 생산자는 `satisfies` 로 맞춘다.
 */
export interface ShellChrome {
  // 하단 공지 바를 띄울지. 생략하면 띄우지 않는다.
  //
  // 기본을 "감춤" 으로 둔 이유: 관리자 셸 아래 화면은 거의 전부 작업 화면이다(사용자 관리, 조직
  // 관리, 스토리지, 권한 관리, API 등록). 이들은 세로를 목록과 패널에 다 쓰고 하단에 자기 바를
  // 띄우기도 한다. 공지 줄이 늘 깔려 있으면 둘 다 좁아진다.
  //
  // 공지가 필요한 자리는 사람이 들어와 머무는 로비(관리자 홈) 하나다. 그래서 선언도 하나면 된다.
  // 기본을 "띄움" 으로 두면 그 하나를 위해 나머지 전부가 `false` 를 반복 선언해야 하고, 새 화면을
  // 만들 때마다 그 한 줄을 기억해야 한다.
  bottomBar?: boolean;
}

/**
 * 기본값 판정. 선언하지 않은 화면은 감춘다는 규칙을 여기 한 곳에 둔다.
 *
 * 비교를 뒤집으면 로비를 뺀 모든 화면에 공지 줄이 되살아난다. 인라인 표현식으로 두면 그 규칙이
 * 셸 마크업 안에 묻히므로, 이름 붙인 함수로 꺼내 테스트로 고정한다.
 */
export function shouldShowBottomBar(chrome: ShellChrome | undefined): boolean {
  return chrome?.bottomBar === true;
}
