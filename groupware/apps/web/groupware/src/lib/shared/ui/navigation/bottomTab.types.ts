/**
 * 하단 탭 한 칸의 표시 계약(BottomTabBar)
 *
 * 바는 이 모양만 알고 무엇이 담기는지는 모른다. 지금 담는 것은 끝내지 않은 영상 작업이지만,
 * 같은 자리를 다른 목록(열어 둔 항목, 최소화한 창)이 쓸 수 있어야 해서 도메인 어휘를 두지 않는다.
 * 도메인 값 → 이 모양의 변환은 그 도메인이 갖는다(예: marketing-video 의 workTabs).
 */
export interface BottomTabItem {
  // 이 탭을 가리키는 값. 호출부가 소유하며 onSelect 로 그대로 돌아온다.
  id: string;
  label: string;
  // 라벨 오른쪽 배지(예: '42%', '결과 확인'). 없으면 그리지 않는다.
  badge?: string;
  // 0~100. 있으면 칩 아래에 얇은 진행선을 깐다. 배지의 숫자를 눈으로 대신 읽는 자리다.
  percent?: number;
  // 아직 일이 돌고 있는가. 참이면 스피너를 앞에 둔다.
  busy?: boolean;
  // 마우스를 올렸을 때의 전체 설명. 라벨은 좁아 잘리므로 원문을 여기 담는다.
  title?: string;
  // 이 탭에서 그 일을 끝낼 수 있는가. 참이면 닫기(×)를 그린다.
  //
  // 항목마다 갈리는 이유: 끝낸다는 말의 무게가 다르다. 적어 둔 것을 버리는 것은 이 탭에서 끝나지만,
  // 돌고 있는 유료 생성을 끊는 것은 되돌릴 수 없어 확인을 거쳐야 하고 그 자리는 창 안이다.
  closable?: boolean;
}
